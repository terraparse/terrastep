def _config_table() -> str:
    default = Config()
    rows = [
        f"| `scan_dirs` | `{list(default.scan_dirs)!r}` | {CONFIG_HELP['scan_dirs']} |",
        f"| `index_file` | `{default.index_file!r}` | {CONFIG_HELP['index_file']} |",
        f"| `exclude` | `{list(default.exclude)!r}` | {CONFIG_HELP['exclude']} |",
        f"| `id_floor` | `{default.id_floor!r}` | {CONFIG_HELP['id_floor']} |",
        f"| `in_progress_cap` | `{default.in_progress_cap!r}` | {CONFIG_HELP['in_progress_cap']} |",
        f"| `[aliases]` | (none) | {CONFIG_HELP['aliases']} |",
        f"| `warn_bare_section` | `{default.warn_bare_section!r}` | {CONFIG_HELP['warn_bare_section']} |",
        f"| `[migrate] changelog` | (none) | {CONFIG_HELP['migrate.changelog']} |",
        f"| `[migrate] legacy_dir` | (none) | {CONFIG_HELP['migrate.legacy_dir']} |",
        *_brain_budget_config_rows(),
    ]
    return "| Key | Default | Meaning |\n|---|---|---|\n" + "\n".join(rows)


def _measures_table() -> str:
    limits = Config().brain_budget.limits
    rows = budget.FORMAT_DEFINITION["complexity"]["rows"]
    lines = ["| Measure | Label | Default limit |", "|---|---|---:|"]
    lines += [f"| `{machine}` | {label} | {getattr(limits, machine)} |" for machine, label in rows]
    return "\n".join(lines)


def _brain_budget_code_table() -> str:
    rows = [f"| `{code}` | {msg} |" for code, msg in core.FAILURE_CODES.items()
            if code.startswith("brain-budget-")]
    return "| Code | Meaning |\n|---|---|\n" + "\n".join(rows)


def _states_and_types_table() -> str:
    return (
        "| | |\n|---|---|\n"
        f"| `status` | one of {list(core.STATES)} |\n"
        f"| A `note`'s `status` | one of {list(core.NOTE_STATES)} |\n"
        f"| `type` | one of {list(core.TYPES)} (`{core.PLAN_TYPES[0]}` is the only type "
        f"checked against the body shape below) |\n"
        f"| `closed_reason`, when `status: closed` | one of {list(core.CLOSED_REASONS)} |"
    )


def _role_alias_table() -> str:
    rows = [f"| `{role}` | {', '.join(f'`{p}`' for p in patterns)} |"
            for role, patterns in core.ROLE_ALIASES.items()]
    return "| Role | Heading patterns (prefix match) |\n|---|---|\n" + "\n".join(rows)



"""Generates journal/terrastep_101.md and the bundled Claude Code skill from
this package's own constants (core.py, config.py, cli.py) — one source of
truth, not hand-written prose that can drift from the rules it describes.

  terrastep skill build     regenerates the checked-in copies (maintainer use)
  terrastep skill install   copies the bundled, already-generated skill into
                             another repo's .claude/skills/ (end-user use)

This module only renders text. It never decides where the result is written;
callers (cli.py) do that.
"""

